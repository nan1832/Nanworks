def fmt_p(p):
    if np.isnan(p): return 'NA'
    if p < 1e-4: return '<1e-4'
    return f'{p:.4f}'

def compute_all(lga_dict, target_dict, model, modality):
    n = len(list(target_dict.values())[0])
    rows = []
    for mname, mvals in lga_dict.items():
        assert len(mvals) == n, f'{model} {modality} {mname}: {len(mvals)} != {n}'
        top3 = sorted(range(n), key=lambda i: mvals[i], reverse=True)[:3]
        row = {'model': model, 'modality': modality, 'metric': mname, 'n': n, 'top3': top3}
        for tname, tvals in target_dict.items():
            rho, p = stats.spearmanr(mvals, tvals)
            row[f'rho_{tname}'] = rho
            row[f'p_{tname}'] = p
        rows.append(row)
    return rows

