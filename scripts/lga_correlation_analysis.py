# Derived metrics
# ============================================================
def add_derived(lga_dict):
    """Add derived metrics: M_conflict, M_newn_x_1mcos, M_abscos_x_newn"""
    d = lga_dict['M_dot']
    c = lga_dict['M_cos']
    n = lga_dict['M_new_norm']
    lga_dict['M_conflict'] = [-x for x in d]
    lga_dict['M_newn_x_1mcos'] = [nn*(1-cc) for nn,cc in zip(n, c)]
    lga_dict['M_abscos_x_newn'] = [abs(cc)*nn for cc,nn in zip(c, n)]
    return lga_dict

