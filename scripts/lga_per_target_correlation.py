# ============================================================
# Compute correlations
# ============================================================
def fmt_p(p):
    if p is None or np.isnan(p): return 'NA'
    if p < 1e-4: return '<1e-4'
    return f'{p:.4f}'

targets_order = ['Req','Gen','Loc','Port','Comb3']
target_labels = {'Req':'Request','Gen':'Generality','Loc':'Locality','Port':'Portability','Comb3':'Combined3'}
metrics_order = ['M_dot','M_cos','M_new_norm','M_pos_ratio','M_conflict','M_newn_x_1mcos','M_abscos_x_newn']

all_results = {}

for key in [('LLaVA','visual'),('LLaVA','text'),('BLIP2','visual'),('BLIP2','text'),
            ('InstructBLIP','visual'),('InstructBLIP','text'),('Qwen2.5-VL','visual'),('Qwen2.5-VL','text')]:
    model, modality = key
    d = data[key]
    l = lga[key]
    n = len(d['Req'])

    results_for_key = {}
    for tname in targets_order:
        tvals = d[tname]
        best_rho = 0; best_metric = ''; best_top3 = []
        metric_results = []
        for mname in metrics_order:
            mvals = l[mname]
            assert len(mvals) == n, f'{key} {mname}: {len(mvals)} != {n}'
            rho, p = stats.spearmanr(mvals, tvals)
            top3 = sorted(range(n), key=lambda i: mvals[i], reverse=True)[:3]
            metric_results.append({'metric': mname, 'rho': rho, 'p': p, 'top3': top3})
            if not np.isnan(rho) and abs(rho) > abs(best_rho):
                best_rho = rho; best_metric = mname; best_top3 = top3

        # True best layer for this target
        if not all(np.isnan(x) for x in tvals):
            true_best = max(range(n), key=lambda i: tvals[i])
            true_best_val = tvals[true_best]
            # Check for ties
            true_bests = [i for i in range(n) if abs(tvals[i] - true_best_val) < 1e-6]
        else:
            true_bests = []

        results_for_key[tname] = {
            'metrics': metric_results,
            'best_metric': best_metric,
            'best_rho': best_rho,
            'best_top3': best_top3,
            'true_bests': true_bests,
        }
    all_results[key] = results_for_key

