for key in [('LLaVA','visual'),('LLaVA','text'),('BLIP2','visual'),('BLIP2','text'),
            ('InstructBLIP','visual'),('InstructBLIP','text'),('Qwen2.5-VL','visual'),('Qwen2.5-VL','text')]:
    model, modality = key
    for tname in targets_order:
        r = all_results[key][tname]
        bm = r['best_metric']; br = r['best_rho']; bt3 = r['best_top3']; tb = r['true_bests']
        # Find best with p<0.05
        valid = [m for m in r['metrics'] if not np.isnan(m['rho']) and m['p'] < 0.05]
        if valid:
            best_valid = max(valid, key=lambda m: abs(m['rho']))
            bm = best_valid['metric']; br = best_valid['rho']; bt3 = best_valid['top3']
            bp = best_valid['p']
        else:
            bp = [m for m in r['metrics'] if m['metric']==bm][0]['p'] if bm else float('nan')

        hit = int(any(t in tb for t in bt3)) if tb and bt3 else 0
        tb_str = str(tb[:5]) if len(tb)>5 else str(tb)
        rho_s = f'{br:.4f}' if not np.isnan(br) else 'NA'
        print(f"| {model} | {modality} | {target_labels[tname]} | `{bm}` | {rho_s} | {fmt_p(bp)} | {bt3[0] if bt3 else '-'} | {bt3[0] if bt3 else '-'},{bt3[1] if len(bt3)>1 else '-'},{bt3[2] if len(bt3)>2 else '-'} | {tb_str} | {hit} |")

